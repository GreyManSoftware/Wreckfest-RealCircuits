# Python
# --------------------------------------------------------------------------------------------


def py_type(t: TypeRef) -> str:
    if t.kind == "string":
        return "str"
    if t.kind == "number":
        return "float"
    if t.kind == "integer":
        return "int"
    if t.kind == "boolean":
        return "bool"
    if t.kind in ("enum", "object"):
        assert t.name
        return t.name
    if t.kind == "array":
        assert t.item
        return f"list[{py_type(t.item)}]"
    if t.kind == "map":
        assert t.item
        return f"dict[str, {py_type(t.item)}]"
    raise AssertionError(t.kind)


def py_from(t: TypeRef, expr: str, depth: int = 0) -> str:
    v = f"v{depth}"
    if t.kind == "string":
        return f"str({expr})"
    if t.kind == "number":
        return f"float({expr})"
    if t.kind == "integer":
        return f"int({expr})"
    if t.kind == "boolean":
        return f"bool({expr})"
    if t.kind == "enum":
        return f"{t.name}({expr})"
    if t.kind == "object":
        return f"{t.name}.from_dict({expr})"
    if t.kind == "array":
        assert t.item
        return f"[{py_from(t.item, v, depth + 1)} for {v} in {expr}]"
    if t.kind == "map":
        assert t.item
        return f"{{k{depth}: {py_from(t.item, v, depth + 1)} for k{depth}, {v} in {expr}.items()}}"
    raise AssertionError(t.kind)


def py_to(t: TypeRef, expr: str, depth: int = 0) -> str:
    v = f"v{depth}"
    if t.kind in ("string", "number", "integer", "boolean"):
        return expr
    if t.kind == "enum":
        return f"{expr}.value"
    if t.kind == "object":
        return f"{expr}.to_dict()"
    if t.kind == "array":
        assert t.item
        return f"[{py_to(t.item, v, depth + 1)} for {v} in {expr}]"
    if t.kind == "map":
        assert t.item
        return f"{{k{depth}: {py_to(t.item, v, depth + 1)} for k{depth}, {v} in {expr}.items()}}"
    raise AssertionError(t.kind)


def py_literal(t: TypeRef, v: Any) -> str:
    if t.kind == "enum":
        return f"{t.name}.{snake(v).upper()}"
    if t.kind == "boolean":
        return "True" if v else "False"
    if t.kind == "number":
        return repr(float(v))
    if t.kind == "integer":
        return str(int(v))
    if t.kind == "string":
        return json.dumps(v)
    if t.kind == "array":
        assert t.item
        return "[" + ", ".join(py_literal(t.item, x) for x in v) + "]"
    raise SystemExit(f"unsupported default for {t.kind}")


def py_doc(lines: list[str], text: str | None, indent: str) -> None:
    if not text:
        return
    body = [b.replace('"""', "'''") for b in doc_lines(text)]
    if len(body) == 1:
        lines.append(f'{indent}"""{body[0]}"""')
    else:
        lines.append(f'{indent}"""{body[0]}')
        lines.extend(f"{indent}{b}" for b in body[1:])
        lines.append(f'{indent}"""')


def gen_py(model: Model) -> str:
    lines = [
        f"# {HEADER}",
        '"""Track spec types generated from the JSON Schema."""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from dataclasses import dataclass",
        "from enum import StrEnum",
        "from typing import Any",
        "",
        "",
    ]
    names: list[str] = []
    for e in model.enums:
        names.append(e.name)
        lines.append(f"class {e.name}(StrEnum):")
        if e.description or e.title:
            py_doc(lines, e.description or e.title, "    ")
            lines.append("")
        for v in e.values:
            lines.append(f"    {snake(v).upper()} = {json.dumps(v)}")
        lines.append("")
        lines.append("")
    for o in model.objects:
        names.append(o.name)
        lines.append("@dataclass(kw_only=True)")
        lines.append(f"class {o.name}:")
        if o.description or o.title:
            py_doc(lines, o.description or o.title, "    ")
            lines.append("")
        for p in o.props:
            pt = py_type(p.type)
            if p.required:
                lines.append(f"    {snake(p.json_name)}: {pt}")
            else:
                lines.append(f"    {snake(p.json_name)}: {pt} | None = None")
        lines.append("")
        lines.append("    @classmethod")
        lines.append(f"    def from_dict(cls, data: Mapping[str, Any]) -> {o.name}:")
        lines.append("        return cls(")
        for p in o.props:
            key = json.dumps(p.json_name)
            if p.required:
                conv = py_from(p.type, f"data[{key}]")
            else:
                conv = f"None if data.get({key}) is None else {py_from(p.type, f'data[{key}]')}"
            lines.append(f"            {snake(p.json_name)}={conv},")
        lines.append("        )")
        lines.append("")
        lines.append("    def to_dict(self) -> dict[str, Any]:")
        lines.append("        out: dict[str, Any] = {}")
        for p in o.props:
            attr = f"self.{snake(p.json_name)}"
            key = json.dumps(p.json_name)
            if p.required:
                lines.append(f"        out[{key}] = {py_to(p.type, attr)}")
            else:
                lines.append(f"        if {attr} is not None:")
                lines.append(f"            out[{key}] = {py_to(p.type, attr)}")
        lines.append("        return out")
        if all_defaults(o):
            lines.append("")
            lines.append("    @classmethod")
            lines.append(f"    def defaults(cls) -> {o.name}:")
            lines.append(f'        """Schema defaults for {o.name}."""')
            lines.append("        return cls(")
            for p in o.props:
                lines.append(f"            {snake(p.json_name)}={py_literal(p.type, p.default)},")
            lines.append("        )")
        lines.append("")
        lines.append("")
    lines.append("__all__ = [")
    lines.extend(f'    "{n}",' for n in sorted(names))
    lines.append("]")
    return "\n".join(lines).rstrip() + "\n"


def gen_py_init() -> str:
    return "\n".join(
        [
            f"# {HEADER}",
            '"""Generated track spec types plus copies of the schema and rules JSON."""',
            "",
            "from .track_spec import *  # noqa: F403",
            "from .track_spec import __all__ as __all__",
            "",
        ]
    )


# --------------------------------------------------------------------------------------------
# Driver
# --------------------------------------------------------------------------------------------


def outputs() -> dict[Path, bytes]:
    """Files to write. The Python target always; TypeScript and C# only when their app folders
    (``src/web``, ``src/Api``) exist, so the generator also runs in a checkout without the web app."""
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    model = load_model(schema)
    files: dict[Path, bytes] = {
        PY_DIR / "track_spec.py": gen_py(model).encode(),
        PY_DIR / "__init__.py": gen_py_init().encode(),
    }
    dirs = [PY_DIR]
    if (REPO / "src" / "web").is_dir():
        files[TS_DIR / "trackSpec.ts"] = gen_ts(model).encode()
        dirs.append(TS_DIR)
    if (REPO / "src" / "Api").is_dir():
        files[CS_DIR / "TrackSpec.g.cs"] = gen_cs(model).encode()
        dirs.append(CS_DIR)
    for name in COPIED_FILES:
        data = (SCHEMA_DIR / name).read_bytes().replace(b"\r\n", b"\n")
        for d in dirs:
            files[d / name] = data
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate C#, TypeScript and Python types from the track spec schema.")
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args(argv)

    stale: list[Path] = []
    for path, data in outputs().items():
        current = path.read_bytes().replace(b"\r\n", b"\n") if path.exists() else None
        if current == data:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

    rel = [p.relative_to(REPO).as_posix() for p in stale]
    if args.check:
        if rel:
            print("Generated files are out of date (run: py schema/codegen/generate.py):")
            print("\n".join(f"  {r}" for r in rel))
            return 1
        print("Generated files are up to date.")
        return 0
    print("\n".join(f"wrote {r}" for r in rel) if rel else "Generated files already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
