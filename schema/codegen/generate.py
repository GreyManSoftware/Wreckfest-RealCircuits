"""Generate C#, TypeScript and Python types from schema/track-spec.schema.json.

Stdlib only. Run from anywhere:

    py schema/codegen/generate.py           # write generated files
    py schema/codegen/generate.py --check   # exit 1 if any generated file is stale

The emitter supports the schema subset used by the track spec: named object and string-enum types
in ``$defs``, string aliases (``$defs`` of ``type: string`` without ``enum``), ``string``,
``number``, ``integer`` and ``boolean`` properties, arrays, and maps (``additionalProperties``
with a ``$ref``). Inline object or enum schemas are rejected: give them a ``$defs`` entry.
The schema and rules JSON files are also copied next to each target's generated code so every
runtime (browser bundle, API assembly, Python package) carries its own copy. The TypeScript and C#
targets are skipped when ``src/web`` or ``src/Api`` is absent (e.g. the standalone pipeline repo).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
SCHEMA_DIR = REPO / "schema"
SCHEMA_PATH = SCHEMA_DIR / "track-spec.schema.json"
COPIED_FILES = ["track-spec.schema.json", "track-rules.json"]

TS_DIR = REPO / "src" / "web" / "src" / "generated"
CS_DIR = REPO / "src" / "Api" / "Generated"
PY_DIR = REPO / "geom" / "src" / "trackgen_geom" / "generated"

HEADER = "DO NOT EDIT. Generated by schema/codegen/generate.py from schema/track-spec.schema.json."
CS_NAMESPACE = "TrackGen.Api.Generated"


# --------------------------------------------------------------------------------------------
# Model
# --------------------------------------------------------------------------------------------


@dataclass
class TypeRef:
    kind: str  # string | number | integer | boolean | enum | object | array | map
    name: str | None = None  # enum/object name
    alias: str | None = None  # string alias name (e.g. Id)
    item: TypeRef | None = None  # array item / map value


@dataclass
class Prop:
    json_name: str
    type: TypeRef
    required: bool
    description: str | None
    title: str | None
    default: Any = None
    has_default: bool = False


@dataclass
class ObjectType:
    name: str
    description: str | None
    title: str | None
    props: list[Prop] = field(default_factory=list)


@dataclass
class EnumType:
    name: str
    description: str | None
    title: str | None
    values: list[str] = field(default_factory=list)


@dataclass
class AliasType:
    name: str
    description: str | None


@dataclass
class Model:
    objects: list[ObjectType]
    enums: list[EnumType]
    aliases: list[AliasType]


def load_model(schema: dict[str, Any]) -> Model:
    defs: dict[str, Any] = schema.get("$defs", {})
    objects: list[ObjectType] = []
    enums: list[EnumType] = []
    aliases: list[AliasType] = []
    kinds: dict[str, str] = {}

    for name, d in defs.items():
        if d.get("type") == "string" and "enum" in d:
            kinds[name] = "enum"
        elif d.get("type") == "object":
            kinds[name] = "object"
        elif d.get("type") == "string":
            kinds[name] = "alias"
        else:
            raise SystemExit(f"$defs/{name}: unsupported definition")

    def resolve(s: dict[str, Any], where: str) -> TypeRef:
        if "$ref" in s:
            ref = s["$ref"]
            if not ref.startswith("#/$defs/"):
                raise SystemExit(f"{where}: only local $defs refs are supported")
            target = ref[len("#/$defs/") :]
            kind = kinds[target]
            if kind == "alias":
                return TypeRef("string", alias=target)
            return TypeRef(kind, name=target)
        t = s.get("type")
        if t in ("string", "number", "integer", "boolean"):
            if "enum" in s:
                raise SystemExit(f"{where}: inline enums are not supported; add a $defs entry")
            return TypeRef(t)
        if t == "array":
            return TypeRef("array", item=resolve(s["items"], where + "[]"))
        if t == "object" and isinstance(s.get("additionalProperties"), dict) and "properties" not in s:
            return TypeRef("map", item=resolve(s["additionalProperties"], where + "{}"))
        raise SystemExit(f"{where}: unsupported or inline schema; add a $defs entry")

    def build_object(name: str, d: dict[str, Any]) -> ObjectType:
        required = set(d.get("required", []))
        obj = ObjectType(name, d.get("description"), d.get("title"))
        for pname, ps in d.get("properties", {}).items():
            target = None
            if "$ref" in ps:
                target = defs[ps["$ref"][len("#/$defs/") :]]
            desc = ps.get("description") or (target or {}).get("description")
            title = ps.get("title") or (target or {}).get("title")
            obj.props.append(
                Prop(
                    json_name=pname,
                    type=resolve(ps, f"{name}.{pname}"),
                    required=pname in required,
                    description=desc,
                    title=title,
                    default=ps.get("default"),
                    has_default="default" in ps,
                )
            )
        return obj

    objects.append(build_object(schema["title"], schema))
    for name, d in defs.items():
        if kinds[name] == "enum":
            enums.append(EnumType(name, d.get("description"), d.get("title"), list(d["enum"])))
        elif kinds[name] == "object":
            objects.append(build_object(name, d))
        else:
            aliases.append(AliasType(name, d.get("description")))
    return Model(objects, enums, aliases)


# --------------------------------------------------------------------------------------------
# Naming helpers
# --------------------------------------------------------------------------------------------


def pascal(s: str) -> str:
    parts = re.split(r"[_\-\s]+", s)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def camel(s: str) -> str:
    p = pascal(s)
    return p[:1].lower() + p[1:]


def snake(s: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return re.sub(r"[\-\s]+", "_", s).lower()


def doc_lines(text: str) -> list[str]:
    return [line.rstrip() for line in text.splitlines() if line.strip()]


def ts_str(v: Any) -> str:
    """JSON literal with single-quoted strings (matches the web project's style)."""
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(v, list):
        return "[" + ", ".join(ts_str(x) for x in v) + "]"
    return json.dumps(v)


def all_defaults(obj: ObjectType) -> bool:
    return bool(obj.props) and all(p.has_default for p in obj.props)


# --------------------------------------------------------------------------------------------
# TypeScript
# --------------------------------------------------------------------------------------------


def ts_type(t: TypeRef) -> str:
    if t.kind == "string":
        return t.alias or "string"
    if t.kind in ("number", "integer"):
        return "number"
    if t.kind == "boolean":
        return "boolean"
    if t.kind in ("enum", "object"):
        assert t.name
        return t.name
    if t.kind == "array":
        assert t.item
        return f"{ts_type(t.item)}[]"
    if t.kind == "map":
        assert t.item
        return f"Record<string, {ts_type(t.item)}>"
    raise AssertionError(t.kind)


def ts_doc(lines: list[str], text: str | None, indent: str = "") -> None:
    if not text:
        return
    body = [b.replace("*/", "* /") for b in doc_lines(text)]
    if len(body) == 1:
        lines.append(f"{indent}/** {body[0]} */")
    else:
        lines.append(f"{indent}/**")
        lines.extend(f"{indent} * {b}" for b in body)
        lines.append(f"{indent} */")


def gen_ts(model: Model) -> str:
    lines = [f"// {HEADER}", ""]
    for a in model.aliases:
        ts_doc(lines, a.description)
        lines.append(f"export type {a.name} = string")
        lines.append("")
    for e in model.enums:
        ts_doc(lines, e.description or e.title)
        lines.append(f"export type {e.name} = " + " | ".join(ts_str(v) for v in e.values))
        lines.append(f"export const {camel(e.name)}Values: readonly {e.name}[] = {ts_str(e.values)}")
        lines.append("")
    for o in model.objects:
        ts_doc(lines, o.description or o.title)
        lines.append(f"export interface {o.name} {{")
        for p in o.props:
            ts_doc(lines, p.description or p.title, "  ")
            opt = "" if p.required else "?"
            lines.append(f"  {p.json_name}{opt}: {ts_type(p.type)}")
        lines.append("}")
        lines.append("")
        if all_defaults(o):
            lines.append(f"/** Schema defaults for {o.name}. */")
            lines.append(f"export const {camel(o.name)}Defaults: {o.name} = {{")
            for p in o.props:
                lines.append(f"  {p.json_name}: {ts_str(p.default)},")
            lines.append("}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------------------------
# C#
# --------------------------------------------------------------------------------------------


def cs_type(t: TypeRef) -> str:
    if t.kind == "string":
        return "string"
    if t.kind == "number":
        return "double"
    if t.kind == "integer":
        return "int"
    if t.kind == "boolean":
        return "bool"
    if t.kind in ("enum", "object"):
        assert t.name
        return t.name
    if t.kind == "array":
        assert t.item
        return f"IReadOnlyList<{cs_type(t.item)}>"
    if t.kind == "map":
        assert t.item
        return f"IReadOnlyDictionary<string, {cs_type(t.item)}>"
    raise AssertionError(t.kind)


def xml_escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def cs_doc(lines: list[str], text: str | None, indent: str) -> None:
    if not text:
        return
    lines.append(f"{indent}/// <summary>")
    lines.extend(f"{indent}/// {xml_escape(b)}" for b in doc_lines(text))
    lines.append(f"{indent}/// </summary>")


def cs_literal(t: TypeRef, v: Any) -> str:
    if t.kind == "enum":
        return f"{t.name}.{pascal(v)}"
    if t.kind == "boolean":
        return "true" if v else "false"
    if t.kind == "number":
        return repr(float(v))
    if t.kind == "integer":
        return str(int(v))
    if t.kind == "string":
        return json.dumps(v)
    if t.kind == "array":
        assert t.item
        return "[" + ", ".join(cs_literal(t.item, x) for x in v) + "]"
    raise SystemExit(f"unsupported default for {t.kind}")


def gen_cs(model: Model) -> str:
    lines = [
        "// <auto-generated>",
        f"// {HEADER}",
        "// </auto-generated>",
        "#nullable enable",
        "",
        "using System.Text.Json.Serialization;",
        "",
        f"namespace {CS_NAMESPACE};",
        "",
    ]
    for e in model.enums:
        cs_doc(lines, e.description or e.title, "")
        lines.append(f"[JsonConverter(typeof(JsonStringEnumConverter<{e.name}>))]")
        lines.append(f"public enum {e.name}")
        lines.append("{")
        for v in e.values:
            lines.append(f'    [JsonStringEnumMemberName("{v}")]')
            lines.append(f"    {pascal(v)},")
        lines.append("}")
        lines.append("")
    for o in model.objects:
        cs_doc(lines, o.description or o.title, "")
        lines.append(f"public sealed record {o.name}")
        lines.append("{")
        for i, p in enumerate(o.props):
            if i:
                lines.append("")
            cs_doc(lines, p.description or p.title, "    ")
            lines.append(f'    [JsonPropertyName("{p.json_name}")]')
            if p.required:
                lines.append(f"    public required {cs_type(p.type)} {pascal(p.json_name)} {{ get; init; }}")
            else:
                lines.append("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]")
                lines.append(f"    public {cs_type(p.type)}? {pascal(p.json_name)} {{ get; init; }}")
        if all_defaults(o):
            lines.append("")
            lines.append(f"    /// <summary>Schema defaults for {o.name}.</summary>")
            lines.append(f"    public static {o.name} Defaults => new()")
            lines.append("    {")
            for p in o.props:
                lines.append(f"        {pascal(p.json_name)} = {cs_literal(p.type, p.default)},")
            lines.append("    };")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


